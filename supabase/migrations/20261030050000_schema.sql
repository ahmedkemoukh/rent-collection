-- Tables, constraints and indexes. Money is integer sen (bigint), calendar dates are date,
-- instants are timestamptz. Names follow the brief (section 8).

create extension if not exists btree_gist with schema extensions;

create type public.membership_role as enum ('manager', 'staff');
create type public.invoice_kind as enum ('deposit', 'rent');
create type public.payment_method as enum ('cash', 'bank_transfer', 'online');
create type public.payment_status as enum ('pending_verification', 'approved', 'rejected', 'voided');
create type public.gateway_bill_status as enum ('pending', 'paid', 'failed');

-- user_id columns reference auth.users(id) but have no foreign key: a cross-schema FK makes
-- `prisma db pull` fail (P4002). The seed and the server are the only writers of these columns.

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) > 0),
  created_at timestamptz not null default now()
);

create table public.memberships (
  user_id uuid primary key, -- one organization per staff member or manager
  org_id uuid not null references public.organizations (id) on delete restrict,
  role public.membership_role not null,
  created_at timestamptz not null default now()
);
create index memberships_org_id_idx on public.memberships (org_id);

create table public.units (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  name text not null check (char_length(btrim(name)) > 0),
  created_at timestamptz not null default now(),
  unique (org_id, name),
  unique (id, org_id)
);

create table public.tenants (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  user_id uuid unique,
  full_name text not null check (char_length(btrim(full_name)) > 0),
  email text not null,
  phone text,
  created_at timestamptz not null default now(),
  unique (id, org_id)
);
create index tenants_org_id_idx on public.tenants (org_id);

create table public.leases (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  unit_id uuid not null,
  tenant_id uuid not null,
  start_date date not null,
  end_date date not null,
  monthly_rent_sen bigint not null check (monthly_rent_sen > 0),
  deposit_sen bigint not null check (deposit_sen >= 0),
  created_at timestamptz not null default now(),
  check (end_date >= start_date),
  unique (id, org_id),
  foreign key (unit_id, org_id) references public.units (id, org_id) on delete restrict,
  foreign key (tenant_id, org_id) references public.tenants (id, org_id) on delete restrict,
  -- Both dates are inclusive, hence '[]'. Enforced by the database, so concurrent requests cannot overlap.
  constraint leases_no_overlap exclude using gist (
    unit_id with =,
    daterange(start_date, end_date, '[]') with &&
  )
);
create index leases_org_id_idx on public.leases (org_id);
create index leases_unit_id_org_id_idx on public.leases (unit_id, org_id);
create index leases_tenant_id_org_id_idx on public.leases (tenant_id, org_id);

create table public.invoices (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  lease_id uuid not null,
  kind public.invoice_kind not null,
  period_index integer,
  period_start date,
  period_end date,
  due_date date not null,
  amount_sen bigint not null check (amount_sen > 0),
  created_at timestamptz not null default now(),
  unique (id, org_id),
  -- Deposits have a null period_index, so this also allows at most one deposit per lease.
  unique nulls not distinct (lease_id, period_index),
  foreign key (lease_id, org_id) references public.leases (id, org_id) on delete restrict,
  check (
    (kind = 'deposit' and period_index is null and period_start is null and period_end is null)
    or (
      kind = 'rent'
      and period_index is not null and period_index >= 0
      and period_start is not null and period_end is not null
      and period_end >= period_start
    )
  )
);
create index invoices_org_id_idx on public.invoices (org_id);
create index invoices_lease_id_org_id_idx on public.invoices (lease_id, org_id);

create table public.gateway_bills (
  id text primary key check (char_length(id) >= 20), -- random, generated by the server
  org_id uuid not null references public.organizations (id) on delete restrict,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  status public.gateway_bill_status not null default 'pending',
  transaction_id text,
  paid_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  unique (id, org_id),
  foreign key (lease_id, org_id) references public.leases (id, org_id) on delete restrict
);
create index gateway_bills_org_id_idx on public.gateway_bills (org_id);
create index gateway_bills_lease_id_org_id_idx on public.gateway_bills (lease_id, org_id);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  lease_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  unapplied_sen bigint not null default 0,
  method public.payment_method not null,
  status public.payment_status not null,
  received_at timestamptz not null,
  slip_path text unique,
  gateway_bill_id text unique, -- a bill creates at most one payment, ever
  recorded_by uuid,
  decided_by uuid,
  decided_at timestamptz,
  reason text,
  created_at timestamptz not null default now(),
  unique (id, org_id),
  unique (gateway_bill_id, org_id), -- target for Prisma's one-to-one relation to gateway_bills
  foreign key (lease_id, org_id) references public.leases (id, org_id) on delete restrict,
  foreign key (gateway_bill_id, org_id) references public.gateway_bills (id, org_id) on delete restrict,
  check (unapplied_sen between 0 and amount_sen),
  check (unapplied_sen = 0 or method = 'online'),
  check ((method = 'bank_transfer') = (slip_path is not null)),
  check ((method = 'online') = (gateway_bill_id is not null)),
  check (slip_path is null or slip_path like org_id::text || '/%'),
  check (status not in ('rejected', 'voided') or char_length(btrim(reason)) >= 5)
);
create index payments_lease_id_org_id_idx on public.payments (lease_id, org_id);
create index payments_org_status_received_idx on public.payments (org_id, status, received_at);

create table public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations (id) on delete restrict,
  payment_id uuid not null,
  invoice_id uuid not null,
  amount_sen bigint not null check (amount_sen > 0),
  created_at timestamptz not null default now(),
  unique (payment_id, invoice_id),
  foreign key (payment_id, org_id) references public.payments (id, org_id) on delete restrict,
  foreign key (invoice_id, org_id) references public.invoices (id, org_id) on delete restrict
);
create index payment_allocations_org_id_idx on public.payment_allocations (org_id);
create index payment_allocations_payment_id_org_id_idx on public.payment_allocations (payment_id, org_id);
create index payment_allocations_invoice_id_org_id_idx on public.payment_allocations (invoice_id, org_id);

create table public.audit_log (
  id bigint generated always as identity primary key,
  org_id uuid not null references public.organizations (id) on delete restrict,
  actor_id uuid, -- null when the gateway webhook is the actor
  action text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_log_org_id_created_at_idx on public.audit_log (org_id, created_at);
